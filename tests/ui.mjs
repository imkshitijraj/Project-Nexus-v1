await page.goto('http://127.0.0.1:4173/#settings');
await page.getByLabel('Display name',{exact:true}).fill('Aarav’s workspace');
await page.getByRole('button',{name:'Save profile',exact:true}).click();
const downloadPromise = page.waitForEvent('download');
await page.getByRole('button',{name:'↓ Export backup',exact:true}).click();
const download = await downloadPromise;
const downloadFailure=await download.failure();
if(downloadFailure){console.log('Browser download restricted:',downloadFailure);await writeFile('test-results/test-backup.json',await page.evaluate(()=>JSON.stringify(JSON.parse(localStorage.getItem('stride.workspace.v1')))))}else await download.saveAs('test-results/test-backup.json');
