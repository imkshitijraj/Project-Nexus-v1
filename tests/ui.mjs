import { chromium } from 'playwright';
import path from 'node:path';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
await mkdir('test-results/browser-downloads',{recursive:true});
const browser = await chromium.launch({headless:true,...(process.env.BROWSER_EXECUTABLE_PATH?{executablePath:process.env.BROWSER_EXECUTABLE_PATH}:{}),downloadsPath:path.resolve('test-results/browser-downloads')});
const context = await browser.newContext({viewport:{width:1440,height:1080},acceptDownloads:true});
const page = await context.newPage();
const errors=[],violations=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto('http://127.0.0.1:4173');
await page.waitForSelector('.project-card');
await page.screenshot({path:'test-results/demo-preview.png',fullPage:true});
assert.equal(await page.locator('.project-card').count(),4);
await page.getByRole('button',{name:'+ New project',exact:true}).click();
await page.getByLabel('Project name',{exact:true}).fill('Thesis <img src=x onerror=alert(1)>');
await page.getByLabel('What are you working toward?').fill('An end-to-end verification project.');
await page.locator('#project-category').selectOption('study');
await page.locator('#editor').getByRole('button',{name:'Create project',exact:true}).click();
await page.waitForFunction(()=>location.hash.includes('projects/'));
assert.equal(await page.locator('h1 img').count(),0);
await page.getByRole('button',{name:'+ Add task',exact:true}).click();
await page.getByLabel('Task name',{exact:true}).fill('Complete browser verification');
await page.getByLabel('Priority',{exact:true}).selectOption('High');
await page.getByLabel('Notes (optional)',{exact:true}).fill('Ensure persistence and board transitions work.');
await page.getByRole('button',{name:'Create task',exact:true}).click();
await page.getByRole('button',{name:'Complete browser verification',exact:true}).waitFor();
await page.reload();
await page.getByRole('button',{name:'Complete browser verification',exact:true}).waitFor();
await page.getByRole('button',{name:'▥ Board',exact:true}).click();
await page.locator('.move-task').selectOption('In progress');
assert.equal(await page.locator('.board-column').nth(1).locator('.board-card').count(),1);
await page.locator('.board-title').click();
await page.getByLabel('Task name',{exact:true}).fill('Verified and updated');
await page.getByRole('button',{name:'Save changes',exact:true}).click();
await page.getByRole('button',{name:'☷ List',exact:true}).click();
await page.getByRole('button',{name:'Complete Verified and updated',exact:true}).click();
assert.equal(await page.locator('.project-summary strong').textContent(),'100% complete');
await page.locator('#task-search').fill('no matches');
assert.equal(await page.locator('.empty h3').textContent(),'You’re all clear');
await page.locator('#task-search').fill('Verified');
assert.equal(await page.locator('.task-row').count(),1);
await page.getByRole('button',{name:'Edit project',exact:true}).click();
await page.getByRole('button',{name:'Archive',exact:true}).click();
await page.goto('http://127.0.0.1:4173/#projects');
await page.getByRole('button',{name:'Archived',exact:true}).click();
assert.equal(await page.locator('.project-card').count(),1);
await page.locator('.project-card h3 a').click();
await page.getByRole('button',{name:'Edit project',exact:true}).click();
await page.getByRole('button',{name:'Unarchive',exact:true}).click();
await page.goto('http://127.0.0.1:4173/#calendar');
const month = await page.locator('.calendar-heading h2').textContent();
await page.getByRole('button',{name:'Next month',exact:true}).click();
assert.notEqual(await page.locator('.calendar-heading h2').textContent(),month);
