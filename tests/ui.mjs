await page.waitForFunction(()=>location.hash==='#projects');
assert.equal(await page.locator('.project-card').count(),4);
// Exercise all pages at the required widths; capture accidental horizontal overflow.
for(const width of [320,768,1024,1440]){
  await page.setViewportSize({width,height:1000});
  for(const view of ['overview','projects','tasks','teams','calendar','timeline','budget','risks','reports','notifications','focus','settings']){
    await page.goto(`http://127.0.0.1:4173/#${view}`);
    await page.waitForSelector('h1');
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
    if(overflow)violations.push({width,view});
  }
  if(width===320){await page.goto('http://127.0.0.1:4173/#overview');await page.screenshot({path:'test-results/mobile.png',fullPage:true});}
}
// Independent context confirms corrupt browser storage does not get silently overwritten.
const broken=await browser.newContext();
await broken.addInitScript(()=>localStorage.setItem('stride.workspace.v1','corrupted'));
const recovery=await broken.newPage();await recovery.goto('http://127.0.0.1:4173');
await recovery.locator('#storage-warning').waitFor({state:'visible'});
assert.equal(await recovery.evaluate(()=>localStorage.getItem('stride.workspace.v1')),'corrupted');
assert.deepEqual(violations,[]);
assert.deepEqual(errors,[]);
await writeFile('test-results/browser-results.json',JSON.stringify({passed:true,errors,overflow:violations,downloadVerified:!downloadFailure,downloadLimitation:downloadFailure,checks:['Create and edit project','XSS rendered as text','Create and edit task','Reload persistence','Board transitions','Completion and progress','Search and empty state','Archive and unarchive','Calendar navigation','Focus start/pause/reset','Profile update','Export and import','Invalid import rejected','Due-only shortcut','Cascade project delete','48 responsive page checks','Corrupt storage recovery']},null,2));
console.log('Browser workflows passed. 48 responsive checks passed. No browser errors.');
await browser.close();
